// ABOUTME: Builds the long-form Markdown record stored as dashboard_sections
// ABOUTME: `patient_record_md`. The chat assistant reads it as its primary source.

import { formatLongDate, formatMonthYear, isoDaysFromToday } from "../dates";
import { PERSONA, TIMELINE } from "../persona";
import type { SectionInputs } from "./sections";

/** Lists that appear both as dashboard sections and inside the record. */
export type RecordContent = {
  redFlags: { title: string; body: string }[];
  nutritionFoods: { name: string; goal: string; why: string }[];
  nutritionAvoid: { name: string; body: string }[];
  glossary: { term: string; def: string }[];
};

const fmtValue = (v: number | null) => (v === null ? "—" : String(v));

export function buildPatientRecord(
  today: Date,
  inputs: SectionInputs,
  content: RecordContent,
): string {
  const { psaReadings, labResults, careTeam, planItems, medications } = inputs;
  const iso = (offset: number) => isoDaysFromToday(offset, today);
  const long = (offset: number) => formatLongDate(iso(offset));
  const postRad = psaReadings.filter((r) => r.phase === "post-rad");
  const latestPsa = postRad[postRad.length - 1];

  const panelRows = labResults.filter((r) => !r.category?.startsWith("PSA"));
  const panelDates = [...new Set(panelRows.map((r) => r.date))].sort();
  const recentDate = panelDates[panelDates.length - 1];
  const olderDate = panelDates[0];
  const labLine = (r: (typeof labResults)[number]) =>
    `| ${r.metric} | ${r.value_numeric} ${r.unit} | ${r.reference_range ?? ""} | ${r.flag ?? ""} |`;
  const panelTable = (category: string) => [
    "| Test | Result | Reference | Flag |",
    "| --- | --- | --- | --- |",
    ...panelRows.filter((r) => r.date === recentDate && r.category === category).map(labLine),
  ];
  const metrics = [...new Set(panelRows.map((r) => r.metric))];
  const trendLines = metrics.map((metric) => {
    const older = panelRows.find((r) => r.metric === metric && r.date === olderDate)!;
    const recent = panelRows.find((r) => r.metric === metric && r.date === recentDate)!;
    return `- ${metric}: ${older.value_numeric} (${formatLongDate(olderDate!)}) to ${recent.value_numeric} (${formatLongDate(recentDate!)}) ${recent.unit}${recent.flag ? ` — ${recent.flag}` : ""}`;
  });

  const upcoming = planItems.filter((p) => p.status !== "Completed");
  const team = (name: string) => careTeam.find((m) => m.name === name)!;

  const lines: string[] = [
    `# ${PERSONA.fullName} — Complete Medical Record (Structured Export)`,
    "",
    `> Fictional demonstration record for ${PERSONA.fullName}. Every name, date and value is invented. Generated for the care dashboard demo; not medical advice.`,
    "",
    `Record last updated: ${long(-2)}`,
    "",
    "## 1. Patient Identity",
    "",
    `- Name: ${PERSONA.fullName}`,
    `- Age: ${PERSONA.age}`,
    `- Household: ${PERSONA.household}`,
    `- Primary hospital: ${PERSONA.primaryInstitution}`,
    `- Radiation center: ${PERSONA.radiationInstitution}`,
    "- Primary contact for questions between visits: Maria Torres, RN (nurse navigator)",
    "- Language: English",
    "",
    "## 2. Primary Diagnosis",
    "",
    "- Prostate adenocarcinoma, Gleason 3+4 = 7 (Grade Group 2) at surgery",
    `- Treated with radical prostatectomy in ${formatMonthYear(iso(TIMELINE.surgery))}, then adjuvant radiation to the prostate bed`,
    "- Current status: biochemical recurrence after adjuvant radiation. PSA, undetectable until about six months after radiation, is now detectable and rising slowly. No disease has been located on imaging.",
    "",
    "### Detailed surgical pathology",
    "",
    `Specimen collected ${long(TIMELINE.surgery)} at ${PERSONA.primaryInstitution}. Reviewed by the pathology service there.`,
    "",
    "- Stage: pT3a N0. Focal extraprostatic extension on the left. 0 of 15 lymph nodes involved.",
    "- Grade: Gleason 3+4 = 7, about 30% pattern 4.",
    "- Perineural invasion: present.",
    "- Surgical margin: focally positive, left posterolateral, 1 mm.",
    "- Seminal vesicles: negative. Bladder neck: negative.",
    "- Genomic classifier: 0.71, high-risk range.",
    "",
    "### Biopsy pathology",
    "",
    `Collected ${long(TIMELINE.biopsy)}. Twelve-core systematic biopsy plus two targeted cores from the MRI lesion.`,
    "",
    "- Targeted cores from the left mid-gland lesion: Gleason 3+4 = 7.",
    "- Systematic cores: 4 of 12 positive, mostly Gleason 3+3 = 6.",
    "",
    "## 3. Treatment History (chronological)",
    "",
    `1. ${long(TIMELINE.mri)} — multiparametric prostate MRI after the PSA rose on repeat testing.`,
    `2. ${long(TIMELINE.biopsy)} — MRI-targeted and systematic biopsy at ${PERSONA.primaryInstitution}.`,
    `3. ${long(TIMELINE.preOpPet)} — PSMA PET/CT for staging. No distant disease seen.`,
    `4. ${long(TIMELINE.surgery)} — robot-assisted radical prostatectomy with pelvic lymph node dissection (Dr. Priya Raman).`,
    `5. ${long(TIMELINE.radiationStart)} to ${long(TIMELINE.radiationEnd)} — adjuvant radiation to the prostate bed, 35 fractions, started while PSA was still undetectable, at ${PERSONA.radiationInstitution} (Dr. Samuel Okafor). Tolerated well, with mild bladder irritation that settled within weeks.`,
    "6. No hormone therapy and no chemotherapy to date.",
    "",
    "## 4. PSA Series — Master Timeline (key reference)",
    "",
    "| Date | PSA (ng/mL) | Phase | Note |",
    "| --- | --- | --- | --- |",
    ...psaReadings.map((r) => `| ${r.date} | ${fmtValue(r.value)} | ${r.phase} | ${r.note} |`),
    "",
    `Latest value: ${latestPsa.value} ng/mL on ${formatLongDate(latestPsa.date)}.`,
    "Dr. Raman would move the PET/CT earlier if PSA reaches 0.30 before the scan date. The 0.20 mark is the dashboard's scan-readiness line; the latest value is below it.",
    "Values below 0.01 are reported as undetectable and plotted as 0.008.",
    "",
    `## 5. Most Recent Full Blood Panel — ${formatLongDate(recentDate!)}`,
    "",
    `Drawn at ${PERSONA.primaryInstitution}, ordered by Dr. Helen Brooks alongside the PSA draw.`,
    "",
    "### Comprehensive Metabolic Panel (CMP)",
    "",
    ...panelTable("Comprehensive Metabolic Panel"),
    "",
    "### CBC",
    "",
    ...panelTable("Complete Blood Count (CBC)"),
    "",
    "Two values are flagged: hemoglobin is slightly low and fasting glucose is slightly high. Dr. Brooks plans to recheck both at the next draw.",
    "",
    "## 6. Complete Metric Trends — Every Test Across Every Report",
    "",
    `Two full panels are on file: ${formatLongDate(olderDate!)} and ${formatLongDate(recentDate!)}.`,
    "",
    "### 6.1 Panel metrics, older to recent",
    "",
    ...trendLines,
    "",
    "### 6.2 PSA",
    "",
    `Post-radiation PSA: ${postRad.map((r) => r.value).join(" → ")} ng/mL over ${Math.round((new Date(latestPsa.date).getTime() - new Date(postRad[0].date).getTime()) / 86400000)} days.`,
    "Estimated PSA doubling time across the five post-radiation values: about 2.5 months.",
    "",
    "## 7. Imaging History",
    "",
    `### 7.1 mpMRI prostate — ${long(TIMELINE.mri)}`,
    "",
    "- One PI-RADS 4 lesion in the left mid-gland peripheral zone, about 1.4 cm.",
    "- No clear extension beyond the capsule. No enlarged pelvic nodes.",
    "",
    `### 7.2 PSMA PET/CT — ${long(TIMELINE.preOpPet)} (pre-surgery)`,
    "",
    "- Uptake in the left mid-gland corresponding to the MRI lesion.",
    "- No uptake in lymph nodes, bone or other organs.",
    "",
    `### 7.3 ${PERSONA.radiationInstitution} — radiation planning (${formatMonthYear(iso(TIMELINE.radiationStart))})`,
    "",
    "- Planning CT of the pelvis for the prostate-bed course. No suspicious findings outside the treatment field.",
    "",
    `### 7.4 No imaging since radiation as of ${long(0)}`,
    "",
    `- PSMA PET/CT is scheduled for ${long(TIMELINE.psmaPet)}.`,
    "",
    "## 8. Genomic / Biomarker Status",
    "",
    "- Tumor genomic classifier from surgical tissue: 0.71, high-risk range.",
    "- Inherited-risk (germline) panel: not yet discussed in detail. To be raised after the scan.",
    "- Tumor sequencing: not ordered. Dr. Raman would wait for a lesion to sample; Dr. Whitfield would ask the trial team whether it is needed for eligibility.",
    "",
    "## 9. Care Team",
    "",
    "### Currently active",
    "",
    ...careTeam.map((m) => `- ${m.role}: ${m.name} — ${m.where_based}. ${m.note}.`),
    "",
    "### Pending / scheduled",
    "",
    ...upcoming.map((p) => `- ${formatLongDate(p.event_date!)}: ${p.title}`),
    "",
    "### Historical / cancelled",
    "",
    "- No cancelled appointments in the last year.",
    "",
    "## 10. Visit Notes & Decisions",
    "",
    `### 10.1 ${team("Dr. James Whitfield").name} \u2014 ${PERSONA.radiationInstitution} \u2014 ${long(TIMELINE.secondOpinionVisit)} (in person, second opinion)`,
    "",
    "- Reviewed the five post-radiation PSA values after the latest draw. Concerned by the roughly two-and-a-half-month doubling time.",
    "- Favors starting trial screening this month, in parallel with the scan.",
    "- Would begin a defined course of hormone-based treatment early if eligible, even if the scan is clear.",
    "- Wants blood pressure and cholesterol tighter before any start, and a bone density scan first.",
    "",
    `### 10.2 ${team("Dr. Priya Raman").name} \u2014 ${PERSONA.primaryInstitution} \u2014 ${long(TIMELINE.urologyVisit)} (in person)`,
    "",
    "- Agreed the rise is real and steady, and that the latest value is still below 0.20.",
    "- Wants the PSMA PET/CT on the booked date and a decision visit within two weeks of the report.",
    "- Would hold hormone therapy until the scan is read, unless PSA reaches 0.30 or more before then.",
    "- Open to a trial referral once the scan shows which kind of trial fits.",
    "- Said plainly that this is not an emergency.",
    "",
    "## 11. Lifestyle / Compliance Protocol",
    "",
    "### Daily anchors",
    "",
    "- Walk 30 to 45 minutes every day. Two strength sessions a week.",
    "- Pelvic floor exercises twice daily, as taught by the nurse navigator.",
    "- Consistent sleep schedule. Limit alcohol.",
    "",
    "### Evidence-based foods to emphasize",
    "",
    ...content.nutritionFoods.map((f) => `- ${f.name} (${f.goal}): ${f.why}`),
    "",
    "### Foods to limit",
    "",
    ...content.nutritionAvoid.map((f) => `- ${f.name}: ${f.body}`),
    "",
    "### Current supplements and medications",
    "",
    ...medications.map((m) => `- ${m.item}: ${m.dose} — ${m.purpose} (started by ${m.started_by})`),
    "",
    "## 12. Red-Flag Symptoms (call same-day)",
    "",
    ...content.redFlags.map((r) => `- ${r.title}: ${r.body}`),
    "",
    "## 13. Open Action Items / What's Next",
    "",
    "### Within the next 2–4 weeks",
    "",
    `- ${long(TIMELINE.nextVisit)}: pre-scan check-in with Dr. Raman.`,
    `- ${long(TIMELINE.psmaPet)}: PSMA PET/CT at ${PERSONA.radiationInstitution}.`,
    "- Book the bone density scan so it is done before any hormone therapy.",
    "",
    "### Next two months",
    "",
    `- ${long(TIMELINE.secondOpinionFollowUp)}: second-opinion visit with Dr. Whitfield to review the scan.`,
    "- Repeat ultrasensitive PSA at the same lab, 6 to 8 weeks after the last one.",
    "",
    "### Conditional triggers",
    "",
    "- PSA reaches 0.30 or higher before the scan: ask for the scan to be moved earlier.",
    "- Two draws in a row with a doubling time under two months: ask for the Whitfield follow-up to be moved up.",
    "- New symptoms from the red-flag list: follow the tier shown there, and call the nurse navigator the same day.",
    "- Scan finds one to three nodes: discuss targeted radiation to the nodes.",
    "- Scan finds bone or distant disease: discuss whole-body treatment and the trial.",
    "",
    "## 14. PSA Doubling-Time Bands & Current State",
    "",
    "- More than 12 months: slow.",
    "- 6 to 12 months: intermediate.",
    "- 3 to 6 months: faster than average.",
    "- Under 3 months: fast.",
    "",
    `Current best estimate: about 2.5 months, calculated across the five post-radiation values. The most recent step (${postRad[postRad.length - 2].value} to ${latestPsa.value}) is consistent with that pace.`,
    "",
    "## 15. Known Allergies / Other History",
    "",
    "- No known drug allergies.",
    "- Hypertension and high cholesterol, both treated and stable.",
    "- Mild urinary leakage after surgery, much improved with pelvic floor exercises.",
    "- Never smoked. Retired high-school teacher.",
    "",
    "## 16. Glossary",
    "",
    ...content.glossary.map((g) => `- ${g.term}: ${g.def}`),
    "",
    "## 17. Source File Inventory",
    "",
    "### Visit notes & care planning",
    "",
    "- Care plan summary and visit questions (family-maintained).",
    "",
    "### Pathology",
    "",
    "- Surgical pathology report.pdf (sample document in the Records tab).",
    "",
    "### Imaging",
    "",
    "- MRI, PET/CT and planning CT reports (summarized in section 7).",
    "",
    "### Radiation",
    "",
    "- Radiation treatment summary.pdf (sample document in the Records tab).",
    "",
    "### PSA labs (chronological)",
    "",
    "- Ultrasensitive PSA results.pdf (sample document in the Records tab).",
    "",
    "### Other blood work",
    "",
    "- Metabolic panel and CBC from the two draws in section 6.",
    "",
  ];

  return lines.join("\n");
}
